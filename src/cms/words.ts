/**
 * Every word on the site that is not already content.
 *
 * Section headings, room names, prices and posts have always been CMS
 * documents. What was left was the wording around them — the button that
 * says "Add to cart", the column headed "The roster", the line that says a
 * basket is empty, the label on a contact slip — typed straight into the
 * components, so changing one meant a deploy. All of it lives here now, as
 * the default for a wording document per area of the site, and the admin
 * shows each area as a form beside the rest of that page's content.
 *
 * This file is the single source: the seeds are these objects, the admin
 * forms are generated from their keys (see collections.ts), and the
 * `useWords` hook falls back to them string by string — so a field an
 * editor clears goes back to the committed wording instead of rendering a
 * blank button.
 *
 * `{name}` in a string is a slot filled at render time (see `fill`). Keep
 * the slot when rewording, or the number it stood for goes missing.
 */

